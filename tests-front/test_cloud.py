import sys
from playwright.sync_api import sync_playwright
STUB=open('/home/claude/work/tests-front/stub_cloud.js',encoding='utf8').read()
res=[]
def check(n,c): res.append(bool(c)); print(('PASS ' if c else 'FAIL ')+n)
with sync_playwright() as p:
    b=p.chromium.launch(); errs=[]
    def new(pre="",w=1200):
        pg=b.new_page(viewport={'width':w,'height':1000},locale='fr-FR'); pg.on("pageerror",lambda e:errs.append(str(e)))
        pg.on("dialog",lambda d:d.accept()); pg.route("**/cdn.jsdelivr.net/**",lambda r:r.abort()); pg.add_init_script(pre+STUB); pg.goto("http://localhost:8765/cloud.html"); pg.wait_for_timeout(1000); return pg
    c=new()
    check("projets : seuls les projets actifs proposés", c.locator("#proj option").count()==1 and "Mon site" in c.inner_text("#proj"))
    check("déploiements : 3 lignes, statuts En ligne / Échec", c.locator("#t-dep tbody tr").count()==3 and "En ligne" in c.inner_text("#t-dep") and "Échec" in c.inner_text("#t-dep"))
    check("adresse https seulement : lien rendu, javascript: refusé", c.locator('#t-dep a[href^="https://ald-mon-site-aaaa"]').count()==1 and "javascript:" not in c.inner_html("#t-dep"))
    check("« Ouvrir le site » pointe vers le dernier déploiement valide", c.is_visible("#live") and c.get_attribute("#live","href").startswith("https://ald-mon-site-aaaa"))
    c.click('[data-log="d1"]'); c.wait_for_timeout(300)
    check("journal affiché, HTML non interprété", c.is_visible("#logs") and "[error]" in c.inner_text("#log-body") and c.evaluate("window.__xss")==None and c.locator("#log-body img").count()==0)
    c.click("#deploy"); c.wait_for_timeout(600)
    check("déploiement réussi : message avec l'adresse et nouvelle ligne", "ald-mon-site-new" in c.inner_text("#msg") and c.locator("#t-dep tbody tr").count()==4)
    f=new("window.__fail='index_html_required';"); f.click("#deploy"); f.wait_for_timeout(500)
    check("échec : message clair en français", "index.html" in f.inner_text("#msg"))
    n=new("window.__fail='cloudflare_not_configured';"); n.click("#deploy"); n.wait_for_timeout(500)
    check("Cloudflare non relié : message honnête, bouton réactivé", "Cloudflare" in n.inner_text("#msg") and not n.is_disabled("#deploy"))
    r=new("window.__fail='rate_limited';"); r.click("#deploy"); r.wait_for_timeout(500)
    check("limite horaire : message", "10 déploiements" in r.inner_text("#msg"))
    c.click('[data-rb="d1"]'); c.wait_for_timeout(500)
    check("restauration : appel avec le bon déploiement et message", c.evaluate("window.__calls.some(x=>x.action==='rollback'&&x.deployment_id==='d1')") and "restaurée" in c.inner_text("#msg"))
    check("variables : seul le NOM est affiché", "API_KEY" in c.inner_text("#env-list") and c.input_type if False else "API_KEY" in c.inner_text("#env-list"))
    check("champ valeur de type mot de passe", c.get_attribute("#env-val","type")=="password")
    c.fill("#env-key","mauvais nom"); c.fill("#env-val","x"); c.click('#env-form button[type=submit]'); c.wait_for_timeout(300)
    check("variable : nom invalide refusé", "invalide" in c.inner_text("#env-err").lower())
    c.fill("#env-key","SECRET_TOKEN"); c.fill("#env-val","valeur-secrete"); c.click('#env-form button[type=submit]'); c.wait_for_timeout(500)
    check("variable ajoutée ; la valeur n'apparaît nulle part dans la page", "SECRET_TOKEN" in c.inner_text("#env-list") and "valeur-secrete" not in c.content() and c.input_value("#env-val")=="")
    c.click('[data-envdel="API_KEY"]'); c.wait_for_timeout(500)
    check("variable supprimée", "API_KEY" not in c.inner_text("#env-list"))
    c.fill("#dom","pas un domaine"); c.click('#dom-form button[type=submit]'); c.wait_for_timeout(300)
    check("domaine invalide refusé", "invalide" in c.inner_text("#dom-err").lower())
    c.fill("#dom","app.monsite.ci"); c.click('#dom-form button[type=submit]'); c.wait_for_timeout(500)
    check("domaine ajouté + instruction CNAME", "app.monsite.ci" in c.inner_text("#dom-list") and "CNAME" in c.inner_text("#dom-help") and "ald-mon-site-aaaa.pages.dev" in c.inner_text("#dom-help"))
    a=new("window.__ANON=true;")
    check("visiteur non connecté : redirigé vers la connexion", "connexion" in a.url)
    m=new("",390)
    check("mobile : pas de défilement horizontal", m.evaluate("document.documentElement.scrollWidth<=window.innerWidth+1"))
    print("ERREURS:",sorted(set(errs)))
    check("aucune erreur JS propre (hors CDN)", not [x for x in errs if 'gsap' not in x.lower() and 'ScrollTrigger' not in x])
    b.close()
print(f"{sum(res)}/{len(res)} OK"); sys.exit(0 if all(res) else 1)
